-- MVP3 ADMIN-002: auditoria de promocion y retiro de rol admin.
-- Aplicar con propietario PostgreSQL; transaccion idempotente para objetos nuevos.
BEGIN;

CREATE TABLE IF NOT EXISTS user_role_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    actor_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    previous_is_admin boolean NOT NULL,
    new_is_admin boolean NOT NULL,
    reason varchar(500) NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_role_changed CHECK (previous_is_admin <> new_is_admin),
    CONSTRAINT ck_user_role_no_self CHECK (target_user_id <> actor_user_id),
    CONSTRAINT ck_user_role_reason CHECK (char_length(btrim(reason)) BETWEEN 5 AND 500)
);

CREATE INDEX IF NOT EXISTS idx_user_role_audit_target
    ON user_role_audit (target_user_id, changed_at DESC, id DESC);

GRANT SELECT, INSERT ON user_role_audit TO poliredi_app;
GRANT USAGE, SELECT ON SEQUENCE user_role_audit_id_seq TO poliredi_app;
COMMIT;
