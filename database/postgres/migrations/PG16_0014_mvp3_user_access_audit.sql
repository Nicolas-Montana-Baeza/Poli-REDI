-- APLICAR CON EL ROL PROPIETARIO antes de publicar los endpoints nuevos.
BEGIN;

CREATE TABLE IF NOT EXISTS user_access_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    actor_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    previous_is_blocked boolean NOT NULL,
    new_is_blocked boolean NOT NULL,
    reason varchar(500) NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_user_access_actual_change CHECK (previous_is_blocked <> new_is_blocked),
    CONSTRAINT ck_user_access_no_self CHECK (target_user_id <> actor_user_id),
    CONSTRAINT ck_user_access_reason CHECK (char_length(btrim(reason)) BETWEEN 5 AND 500)
);

CREATE INDEX IF NOT EXISTS idx_user_access_audit_target
    ON user_access_audit (target_user_id, changed_at DESC, id DESC);

-- El usuario runtime solo consulta y añade auditoría, nunca la reescribe.
GRANT SELECT, INSERT ON user_access_audit TO poliredi_app;
GRANT USAGE, SELECT ON SEQUENCE user_access_audit_id_seq TO poliredi_app;

COMMIT;
