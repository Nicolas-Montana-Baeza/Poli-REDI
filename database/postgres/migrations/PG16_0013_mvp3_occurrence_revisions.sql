-- MVP3: varias revisiones para una misma excepción sin perder trazabilidad.
-- Aplicar con psql antes de publicar el backend nuevo. No cambia las vistas
-- de disponibilidad: la tabla de excepciones sigue guardando el estado ACTUAL.
BEGIN;

CREATE TABLE IF NOT EXISTS institutional_activity_schedule_exception_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exception_id integer NOT NULL REFERENCES institutional_activity_schedule_exceptions(id) ON DELETE RESTRICT,
    activity_id integer NOT NULL,
    schedule_id integer NOT NULL,
    original_date date NOT NULL,
    previous_exception_type varchar(30) NOT NULL,
    previous_date date,
    previous_start_time time,
    previous_end_time time,
    previous_reason text NOT NULL,
    new_exception_type varchar(30) NOT NULL,
    new_date date,
    new_start_time time,
    new_end_time time,
    reason text NOT NULL,
    changed_by_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    changed_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_occurrence_revisions_exception
    ON institutional_activity_schedule_exception_revisions(exception_id,id);

-- Reemplaza la prohibición total de UPDATE por revisión auditada.
-- La identidad original permanece inmutable y se registra OLD + NEW.
CREATE OR REPLACE FUNCTION prevent_schedule_exception_rewrite()
RETURNS trigger LANGUAGE plpgsql AS $function$
DECLARE actor_text text;
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id
      OR NEW.activity_id IS DISTINCT FROM OLD.activity_id
      OR NEW.schedule_id IS DISTINCT FROM OLD.schedule_id
      OR NEW.original_date IS DISTINCT FROM OLD.original_date
      OR NEW.created_by_user_id IS DISTINCT FROM OLD.created_by_user_id
      OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'no se puede alterar la identidad de una excepción'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.exception_type IS DISTINCT FROM OLD.exception_type
      OR NEW.new_date IS DISTINCT FROM OLD.new_date
      OR NEW.new_start_time IS DISTINCT FROM OLD.new_start_time
      OR NEW.new_end_time IS DISTINCT FROM OLD.new_end_time
      OR NEW.reason IS DISTINCT FROM OLD.reason THEN
        actor_text := current_setting('poliredi.exception_revision_actor_id',true);
        IF actor_text IS NULL OR actor_text !~ '^[0-9]+$' THEN
          RAISE EXCEPTION 'revisión de sesión sin actor autorizado'
              USING ERRCODE = '23514';
        END IF;
        INSERT INTO institutional_activity_schedule_exception_revisions (
          exception_id,activity_id,schedule_id,original_date,
          previous_exception_type,previous_date,previous_start_time,previous_end_time,previous_reason,
          new_exception_type,new_date,new_start_time,new_end_time,reason,changed_by_user_id
        ) VALUES (
          OLD.id,OLD.activity_id,OLD.schedule_id,OLD.original_date,
          OLD.exception_type,OLD.new_date,OLD.new_start_time,OLD.new_end_time,OLD.reason,
          NEW.exception_type,NEW.new_date,NEW.new_start_time,NEW.new_end_time,NEW.reason,actor_text::integer
        );
    END IF;
    RETURN NEW;
END;
$function$;

-- La función ya estaba asociada al trigger de la migración 0007.
GRANT SELECT,INSERT ON institutional_activity_schedule_exception_revisions TO poliredi_app;
GRANT USAGE,SELECT ON SEQUENCE institutional_activity_schedule_exception_revisions_id_seq TO poliredi_app;
GRANT EXECUTE ON FUNCTION prevent_schedule_exception_rewrite() TO poliredi_app;
COMMIT;
